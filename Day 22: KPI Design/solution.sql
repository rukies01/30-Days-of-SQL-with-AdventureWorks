9.Sales decline Rate: Measures products, customers, or regions with declining sales

Sales decline Rate: Measures products,
WITH BASETABE AS
(
	SELECT P.EnglishProductName AS ProductName,
		Datepart(Year, OrderDate) as OrderYear,
		SUM(F.SalesAmount) as CurrentYearRevenue
	FROM FactInternetSales F
	LEFT JOIN DimProduct P
	ON F.ProductKey = P.ProductKey
	GROUP BY P.EnglishProductName,
		 Datepart(Year, OrderDate)
--ORDER BY  OrderYear 
) ,
PMRevenue AS
(
	SELECT *,
		LAG(CurrentYearRevenue) over (Partition By ProductName Order by OrderYear) AS PreviousYearRevenue
	FROM BASETABE
)
SELECT *,
		(CurrentYearRevenue-PreviousYearRevenue)*100.0/NULLIF(PreviousYearRevenue,0)  as RevenueGrowthRate,
		CASE
			WHEN CurrentYearRevenue<PreviousYearRevenue Then 'Declining'
			ELSE 'Growing'
			END AS SalesGrowthIndicator
FROM PMRevenue

Sales decline Rate: Measures Region
WITH CYREVENUE AS
(
	SELECT Datepart(Year, F.OrderDate) as OrderYear,
		G.EnglishCountryRegionName AS Region,
		SUM(F.SalesAmount) as CurrentYearRevenue
	FROM FactInternetSales F
	LEFT JOIN DimGeography G
	ON F.SalesTerritoryKey = G.SalesTerritoryKey
	GROUP BY G.EnglishCountryRegionName,
		Datepart(Year, F.OrderDate)
	--Order By TotalRevenue DESC
),
PYREVENUE AS
(
	SELECT *,
		LAG(CurrentYearRevenue) OVER (Partition BY Region Order By OrderYear) as PreviousYearRevenue
	FROM CYREVENUE
)
SELECT *,
	(CurrentYearRevenue-PreviousYearRevenue)*100.0/NULLIF(PreviousYearRevenue,0) AS RegionRevenueTrend,
	CASE
	WHEN CurrentYearRevenue<PreviousYearRevenue THEN 'Declining'
	ELSE 'Growing'
	END as RegionGrowthIndicator
FROM PYREVENUE

Sales decline Rate: Measures Customers
WITH BASETABLE AS
(
	SELECT Datepart(Year, F.OrderDate) As OrderYear,
		F.CustomerKey as CustomerKey,
		CONCAT(C.FirstName, ' ', ISNULL(C.MiddleName + ' ', ''), C.LastName) AS CustomerFullName,
		SUM(F.SalesAmount) AS CurrentYearRevenue
		From FactInternetSales F
		LEFT JOIN DimCustomer C
		ON F.CustomerKey = C.CustomerKey
		GROUP BY Datepart(Year, F.OrderDate),
			F.CustomerKey,
			CONCAT(C.FirstName, ' ', ISNULL(C.MiddleName + ' ', ''), C.LastName)
),
PYRevenue AS
(
	SELECT *,
		LAG(CurrentYearRevenue) OVER (Partition by CustomerKey,CustomerFullName
		Order By OrderYear) as PerviouYearRevenue
	FROM BASETABLE
)
SELECT *,
	(CurrentYearRevenue-PerviouYearRevenue)*100.0/NULLIF(PerviouYearRevenue,0) as CustomerRevenueTrend,
	CASE
	WHEN CurrentYearRevenue<PerviouYearRevenue THEN 'Declining'
	ELSE 'Growing' 
	END as CustomerRevenueIndicator
FROM PYRevenue

