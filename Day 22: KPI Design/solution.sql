6.Month-over-Month Revenue Growth:The percentage increase or decrease in revenue compared to the previous month.
WITH MONTHLYREVENUE AS
(
	SELECT Datepart(Year, OrderDate) as OrderYear,
		Datepart(Month, OrderDate) as OrderMonth,
		Sum(SalesAmount) as CurrentMonthRevenue
	FROM FactInternetSales
	Group by Datepart(Year, OrderDate),
		Datepart(Month, OrderDate) 
),
MoM as
(
	SELECT *,
		Lag(CurrentMonthRevenue,1) over (Order By OrderYear,OrderMonth) as PreviousMonthRevenue
	from MONTHLYREVENUE

)
SELECT *,
(CurrentMonthRevenue-PreviousMonthRevenue)*100.0/NULLIF(PreviousMonthRevenue,0) as MoMGrowth
FROM MoM


